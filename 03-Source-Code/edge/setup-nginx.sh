#!/bin/bash
# Task D + E (Mac 2): nginx as HTTPS edge (TLS termination) + round-robin load balancer.
source "$(dirname "$0")/../lib.sh"

EDGE_NAME="edge-mac2"

CERTS="$ROOT/edge/certs"
[ -f "$CERTS/server.crt" ] && [ -f "$CERTS/server.key" ] || {
  echo "Missing $CERTS/server.crt / server.key. Run ./edge/make-certs.sh first"; exit 1; }

say "Installing nginx (skipped if already installed)"
brew list nginx >/dev/null 2>&1 || brew install nginx

NGX="$BREW_PREFIX/etc/nginx"
mkdir -p "$NGX/servers" "$NGX/team-certs" "$BREW_PREFIX/var/log/nginx"
cp "$CERTS/server.crt" "$CERTS/server.key" "$NGX/team-certs/"
chmod 600 "$NGX/team-certs/server.key"

say "Writing $NGX/servers/$TEAM.conf"
cat > "$NGX/servers/$TEAM.conf" <<EOF
# ---------------------------------------------------------------
# $TEAM edge: TLS termination + reverse proxy + load balancer ($EDGE_NAME)
# Generated by cn-project/edge/setup-nginx.sh
# ---------------------------------------------------------------

# Access log that also records WHICH backend served each request
log_format ${TEAM}_lb '\$remote_addr [\$time_local] "\$request" \$status '
                      'upstream=\$upstream_addr upstream_status=\$upstream_status rt=\$request_time';

# The backend pool. No algorithm line = round robin (A, B, A, B ...).
# Replace with "least_conn;" to explain another strategy.
# max_fails/fail_timeout = passive health check: after 1 failed attempt the server is
# skipped for 10s, then retried.
upstream ${TEAM}_backends {
    server $MAC3_IP:$PORT_A max_fails=1 fail_timeout=10s;   # Backend A (Mac 3)
    server $MAC4_IP:$PORT_B max_fails=1 fail_timeout=10s;   # Backend B (Mac 4)
}

# Plain HTTP -> redirect to HTTPS
server {
    listen 80;
    server_name app.$DOMAIN api.$DOMAIN;
    return 301 https://\$host\$request_uri;
}

# HTTPS entry point (TLS terminates here; backends receive plain HTTP)
server {
    listen 443 ssl;
    http2 on;
    server_name app.$DOMAIN api.$DOMAIN;

    ssl_certificate     $NGX/team-certs/server.crt;
    ssl_certificate_key $NGX/team-certs/server.key;
    ssl_protocols       TLSv1.2 TLSv1.3;

    access_log $BREW_PREFIX/var/log/nginx/${TEAM}_access.log ${TEAM}_lb;

    # Evidence headers: which edge answered, which backend address(es) were tried
    add_header X-Edge          $EDGE_NAME always;
    add_header X-Upstream-Addr \$upstream_addr always;

    location / {
        proxy_pass http://${TEAM}_backends;
        proxy_http_version 1.1;
        proxy_set_header Host              \$host;
        proxy_set_header X-Real-IP         \$remote_addr;
        proxy_set_header X-Forwarded-For   \$proxy_add_x_forwarded_for;
        proxy_set_header X-Forwarded-Proto \$scheme;

        # Fail fast and retry the other backend if one is down
        proxy_connect_timeout 2s;
        proxy_read_timeout    5s;
        proxy_next_upstream   error timeout http_502 http_503 http_504;
    }
}
EOF

NGINX="$BREW_PREFIX/bin/nginx"
say "Testing nginx config"
sudo "$NGINX" -t || exit 1

if pgrep -x nginx >/dev/null; then
  say "Reloading nginx"; sudo "$NGINX" -s reload
else
  say "Starting nginx"; sudo "$NGINX"
fi

sleep 1
say "Listening sockets:"
sudo lsof -nP -iTCP -sTCP:LISTEN | grep -E 'nginx' | awk '{print $1, $9}' | sort -u
echo
echo "Logs: tail -f $BREW_PREFIX/var/log/nginx/${TEAM}_access.log"
echo "Stop: sudo nginx -s stop     Reload after edits: sudo nginx -t && sudo nginx -s reload"
